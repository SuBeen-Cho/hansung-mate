"""Generate supabase/seed/reference.sql from data/normalized/{reference,spaces}.json.

The seed is idempotent: it truncates the ref_* tables and reloads them in one transaction.
Apply with the service role (Supabase SQL editor or `psql "$DATABASE_URL" -f ...`).

Run: python3 -I scripts/build-reference-seed.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ref = json.loads((ROOT / "data/normalized/reference.json").read_text(encoding="utf-8"))
spaces = json.loads((ROOT / "data/normalized/spaces.json").read_text(encoding="utf-8"))
holidays = json.loads((ROOT / "data/normalized/holidays.json").read_text(encoding="utf-8"))
calendar = json.loads((ROOT / "data/normalized/academic-calendar.json").read_text(encoding="utf-8"))
cohort = json.loads((ROOT / "data/normalized/cohort-requirements.json").read_text(encoding="utf-8"))
offerings = json.loads((ROOT / "data/normalized/offerings-2026-2.json").read_text(encoding="utf-8"))
graduation = json.loads((ROOT / "data/normalized/graduation-requirements.json").read_text(encoding="utf-8"))
OUT = ROOT / "supabase/seed/reference.sql"


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, cols, rows):
    if not rows:
        return ""
    out = []
    for i in range(0, len(rows), 200):
        chunk = rows[i : i + 200]
        values = ",\n".join("(" + ",".join(q(v) for v in r) + ")" for r in chunk)
        out.append(f"insert into public.{table} ({','.join(cols)}) values\n{values};")
    return "\n".join(out) + "\n"


college_ids = {c["name"]: c["id"] for c in ref["colleges"]}
program_ids = {p["name"]: p["id"] for p in ref["programs"]}

sql = [
    "-- Generated by scripts/build-reference-seed.py. Do not edit by hand.",
    "begin;",
    "truncate public.ref_program_graduation, public.ref_course_offerings, public.ref_cohort_rules, public.ref_cohort_liberal_rules, public.ref_space_observed_slots, public.ref_holidays, public.ref_calendar_spans, public.ref_spaces, public.ref_microdegrees, public.ref_procedure_results, public.ref_procedure_quotas, public.ref_procedures, public.ref_requirement_profiles, public.ref_course_mappings, public.ref_courses, public.ref_program_aliases, public.ref_programs, public.ref_colleges, public.ref_sources, public.ref_dataset_versions;",
]
sql.append(insert("ref_dataset_versions", ["version", "crawled_at", "source_note"],
                  [[ref["schemaVersion"] + "@" + ref["crawledAt"], ref["crawledAt"], "hansung.ac.kr public pages"]]))
sql.append(insert("ref_sources", ["id", "title", "url", "published_at", "accessed_at"],
                  [[s["id"], s["title"], s["url"], s.get("publishedAt"), s.get("accessedAt", ref["crawledAt"])]
                   for s in ref["sources"] if str(s.get("url", "")).startswith("https://")]))
sql.append(insert("ref_colleges", ["id", "name"], [[c["id"], c["name"]] for c in ref["colleges"]]))
sql.append(insert(
    "ref_programs",
    ["id", "name", "college_id", "unit", "kind", "session", "status", "first_slot_allowed", "second_slot_allowed",
     "requirement_profile", "curriculum_url", "graduation_url", "graduation_summary", "source_status"],
    [[p["id"], p["name"], college_ids.get(p.get("college")), p.get("unit"), p["kind"], p.get("session"), p["status"],
      p.get("firstSlotAllowed", True), p.get("secondSlotAllowed", True), p.get("requirementProfile", "UNKNOWN"),
      p.get("curriculumUrl"), p.get("graduationUrl"), p.get("graduationSummary"), p.get("sourceStatus", "UNKNOWN")]
     for p in ref["programs"]],
))
sql.append(insert("ref_program_aliases", ["program_id", "alias"],
                  sorted({(p["id"], a) for p in ref["programs"] for a in p.get("aliases", []) if a and a != p["name"]})))
sql.append(insert("ref_courses", ["code", "name", "credit_milli", "code_verified"],
                  [[c["code"], c["name"], c["creditMilli"], c.get("codeVerified", True)] for c in ref["courses"]]))
mappings = {}
for c in ref["courses"]:
    for m in c["mappings"]:
        pid = program_ids.get(m["program"])
        if not pid:
            continue
        key = (c["code"], pid, m["category"], str(m["recommendedYear"]), str(m["semester"]))
        mappings.setdefault(key, [*key, m.get("categoryAsPublished"), m.get("module"), m.get("partnerUniversity"), m["sourceUrl"]])
sql.append(insert("ref_course_mappings",
                  ["course_code", "program_id", "category", "recommended_year", "semester", "category_as_published", "module",
                   "partner_university", "source_url"], list(mappings.values())))
sql.append(insert("ref_requirement_profiles", ["id", "payload"],
                  [[k, v] for k, v in ref["requirementProfiles"].items() if isinstance(v, dict)]))
procs = ref["procedures"]
sql.append(insert(
    "ref_procedures",
    ["id", "type", "term", "title", "published_at", "apply_start", "apply_end", "result_at", "eligibility", "notes",
     "average_gpa", "source_url"],
    [[p["id"], p["type"], p["term"], p["title"], p.get("publishedAt"), p.get("applyStart"), p.get("applyEnd"),
      p.get("resultAt"), p.get("eligibility"), p.get("notes", []), p.get("averageGpa"), p["sourceUrl"]] for p in procs],
))
quotas = {}
for p in procs:
    for x in p.get("quotas", []):
        quotas[(p["id"], x["unit"])] = [p["id"], x["unit"], x.get("day"), x.get("night"), x.get("total")]
sql.append(insert("ref_procedure_quotas", ["procedure_id", "unit", "day", "night", "total"], list(quotas.values())))
results = {}
for p in procs:
    for x in p.get("results", []):
        results[(p["id"], x["toUnit"])] = [p["id"], x["toUnit"], x["accepted"]]
sql.append(insert("ref_procedure_results", ["procedure_id", "to_unit", "accepted"], list(results.values())))
sql.append(insert("ref_microdegrees", ["id", "name", "md_type", "category", "credit_milli", "year", "courses", "source_url"],
                  [[m["id"], m["name"], m["mdType"], m["category"], m["creditMilli"], m["year"], m.get("courses", []),
                    m["sourceUrl"]] for m in ref["microdegrees"]]))
sql.append(insert(
    "ref_spaces",
    ["id", "name", "building", "group_name", "kind", "capacity_min", "capacity_max", "capacity_verified", "open_time",
     "close_time", "hours_verified", "booking", "features", "notes", "closed_weekends", "closed_holidays", "source_url"],
    [[s["id"], s["name"], s["building"], s["group"], s["kind"], s["capacityMin"], s["capacityMax"],
      s["capacityVerified"], s["open"], s["close"], s["hoursVerified"], s["booking"], s["features"], s["notes"],
      s.get("closedWeekends", False), s.get("closedHolidays", False), s["sourceUrl"]] for s in spaces["spaces"]],
))
slots = []
for day, rooms in spaces["codingLoungeCalendar"]["days"].items():
    for room, ranges in rooms.items():
        for start, end in ranges:
            slots.append([f"coding-{room}", day, start, end])
spans = []
for t in calendar["terms"]:
    spans.append([f"term-{t['term']}", "TERM", f"{t['term']} 학기", t["start"], t["end"], None, t["term"], calendar["source"]])
for i, v in enumerate(calendar["vacations"]):
    spans.append([f"vacation-{i}", "VACATION", v["name"], v["start"], v["end"], None, None, calendar["source"]])
for i, e in enumerate(calendar["exams"]):
    spans.append([f"exam-{i}", "EXAM", e["name"], e["start"], e["end"], None, None, calendar["source"]])
for i, e in enumerate(calendar["events"]):
    spans.append([f"event-{i}", "EVENT", e["name"], e["start"], e["end"], e["type"], e["term"], calendar["source"]])
for i, c in enumerate(calendar["closures"]):
    spans.append([f"closure-{i}", "CLOSURE", c["name"], c["date"], c["date"], None, None, calendar["source"]])
sql.append(insert("ref_calendar_spans", ["id", "kind", "name", "start_day", "end_day", "procedure_type", "applies_term", "source_url"], spans))
sql.append(insert("ref_holidays", ["day", "name", "verified"],
                  [[h["date"], h["name"], h.get("verified", True)] for h in holidays["holidays"]]))
sql.append(insert("ref_space_observed_slots", ["space_id", "day", "start_time", "end_time"], slots))
sql.append(insert("ref_cohort_liberal_rules", ["cohorts", "from_year", "to_year", "total_milli", "rule", "source"],
                  [[r["cohorts"], r["fromYear"], r["toYear"], r["totalMilli"], r, cohort["source"]] for r in cohort["liberalArts"]]))
sql.append(insert("ref_cohort_rules", ["id", "payload", "source"],
                  [[k, cohort[k], cohort["source"]] for k in ("graduationCredits", "majorPre2016", "transfer", "semesterRules")]))
sql.append(insert("ref_course_offerings", ["term", "kind", "group_name", "code", "name", "category", "recommended_year", "credit", "sections"],
                  [[offerings["term"], o["kind"], o["group"], o["code"], o["name"], o["category"], o.get("year"), o["credit"], o["sections"]]
                   for o in offerings["offerings"]]))
sql.append(insert("ref_program_graduation", ["program_id", "found", "kinds", "summary", "confidence", "detail", "collected_at"],
                  [[program_ids[g["program"]], g["found"], "{" + ",".join(g["kinds"]) + "}", g["summary"], g.get("confidence") if g["found"] else None,
                    {k: g.get(k) for k in ("options", "minOptions", "cohortRules", "substitutes", "submission", "sources", "attachmentOnly", "note")},
                    graduation["collectedAt"]] for g in graduation["programs"] if g["program"] in program_ids]))
sql.append("commit;")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(s for s in sql if s) + "\n", encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: programs={len(ref['programs'])} courses={len(ref['courses'])} "
      f"mappings={len(mappings)} procedures={len(procs)} spaces={len(spaces['spaces'])} slots={len(slots)}")
